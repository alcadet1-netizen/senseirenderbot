from aiogram.filters.callback_data import CallbackData

# Callbacks
class DuelDecisionCb(CallbackData, prefix="dueld"):
    id: int
    d: str  # 'a' (accept) or 'x' (decline)
    c: int  # challenger_id
    o: int  # opponent_id

class DuelMoveCb(CallbackData, prefix="duelm"):
    id: int
    u: int
    m: str  # 'dodge_l'/'dodge_r'/'hit_l'/'hit_r'

class DuelSurrenderCb(CallbackData, prefix="duels"):
    id: int
    u: int

class DuelUtilityCb(CallbackData, prefix="duelu"):
    id: int
    u: int
    a: str  # 'auto' | 'reset' | 'open'

class DuelControlOpenCb(CallbackData, prefix="duelopen"):
    id: int

