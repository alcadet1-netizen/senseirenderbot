class DigestService:
    def __init__(self, settings: Settings):
        self.settings = settings
        self.chats: Dict[int, ChatData] = defaultdict(ChatData)
        self.cooldowns: Dict[int, datetime] = {}
        self.generating: set[int] = set()
        self.ai_factory = AIProviderFactory(settings)
        self.digest_number: Dict[int, int] = defaultdict(int)  # Счётчик выпусков
        
    def add_message(
        self, 
        chat_id: int, 
        user_id: int,
        username: str,
        display_name: str,
        text: str,
        reply_to: str = None
    ) -> int:
        """Сохраняем сообщение, возвращаем текущий счётчик"""
        
        if not text or len(text.strip()) < 2:
            return len(self.chats[chat_id].messages)
        
        # Пропускаем команды
        if text.startswith('/'):
            return len(self.chats[chat_id].messages)
            
        msg = ChatMessage(
            user_id=user_id,
            username=username or f"user_{user_id}",
            display_name=display_name[:30],
            text=text[:500],
            timestamp=datetime.now(),
            reply_to=reply_to[:100] if reply_to else None
        )
        
        self.chats[chat_id].messages.append(msg)
        return len(self.chats[chat_id].messages)

    def get_messages(self, chat_id: int, limit: int = 500) -> List[ChatMessage]:
        """Получаем последние N сообщений"""
        messages = list(self.chats[chat_id].messages)
        return messages[-limit:]

    def get_new_messages_count(self, chat_id: int) -> int:
        """Сколько сообщений с последней сводки"""
        chat = self.chats[chat_id]
        total = len(chat.messages)
        return total - chat.last_digest_count

    def mark_digest_done(self, chat_id: int):
        """Отмечаем что сводка сделана"""
        chat = self.chats[chat_id]
        chat.last_digest_count = len(chat.messages)
        chat.last_digest_time = datetime.now()
        self.cooldowns[chat_id] = datetime.now() + timedelta(seconds=self.settings.digest_cooldown)
        self.digest_number[chat_id] += 1

    def format_for_llm(self, chat_id: int, limit: int = 500) -> str:
        """Форматируем для промпта — расширенный формат"""
        messages = self.get_messages(chat_id, limit)
        
        if not messages:
            return ""
        
        lines = []
        prev_user = None
        
        for msg in messages:
            time_str = msg.timestamp.strftime("%H:%M")
            
            # Добавляем контекст ответа
            reply_context = ""
            if msg.reply_to:
                reply_context = f" │ ↩️ отвечает на: «{msg.reply_to[:50]}...»"
            
            # Группируем сообщения одного пользователя
            if msg.display_name != prev_user:
                lines.append(f"\n[{time_str}] 👤 {msg.display_name}:{reply_context}")
            
            lines.append(f"   {msg.text}")
            prev_user = msg.display_name
        
        return "\n".join(lines)

    def get_stats(self, chat_id: int) -> dict:
        """Статистика по участникам (для внутреннего анализа)"""
        messages = self.get_messages(chat_id)
        stats = defaultdict(lambda: {"count": 0, "chars": 0, "replies": 0})
        
        for msg in messages:
            stats[msg.display_name]["count"] += 1
            stats[msg.display_name]["chars"] += len(msg.text)
            if msg.reply_to:
                stats[msg.display_name]["replies"] += 1
        
        return dict(stats)

    def get_active_users(self, chat_id: int) -> List[str]:
        """Список активных участников"""
        stats = self.get_stats(chat_id)
        sorted_users = sorted(stats.items(), key=lambda x: -x[1]['count'])
        return [name for name, _ in sorted_users[:15]]

    def get_topics(self, chat_id: int) -> List[str]:
        """Пытаемся выделить темы"""
        messages = self.get_messages(chat_id)
        
        words = defaultdict(int)
        for msg in messages:
            for word in msg.text.lower().split():
                clean = ''.join(c for c in word if c.isalnum())
                if len(clean) > 5:
                    words[clean] += 1
        
        sorted_words = sorted(words.items(), key=lambda x: -x[1])[:10]
        return [w[0] for w in sorted_words if w[1] > 3]

    def get_time_range(self, chat_id: int) -> str:
        """Временной диапазон сообщений"""
        messages = self.get_messages(chat_id)
        if not messages:
            return "неизвестно"
        
        first = messages[0].timestamp
        last = messages[-1].timestamp
        
        if first.date() == last.date():
            return f"{first.strftime('%d.%m.%Y')} ({first.strftime('%H:%M')} — {last.strftime('%H:%M')})"
        else:
            return f"{first.strftime('%d.%m %H:%M')} — {last.strftime('%d.%m %H:%M')}"

    def can_generate(self, chat_id: int) -> Tuple[bool, int]:
        """Проверяем можно ли генерировать"""
        if chat_id in self.cooldowns:
            if datetime.now() < self.cooldowns[chat_id]:
                remaining = (self.cooldowns[chat_id] - datetime.now()).seconds
                return False, remaining
        return True, 0

